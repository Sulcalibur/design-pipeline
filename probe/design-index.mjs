/**
 * probe/design-index.mjs — tell every future agent where the design truth lives.
 *
 * After a brand record or a probe run is generated, the project gets one
 * idempotent, marker-delimited section listing what exists and how to treat
 * it. Files are linked, not copied: the record stays the single source, the
 * index only points.
 *
 * Upserted into (project root): AGENTS.md, design.md (created if missing),
 * and docs/design/README.md.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

export const MARK_BEGIN = '<!-- design-pipeline:auto begin -->'
export const MARK_END = '<!-- design-pipeline:auto end -->'

function upsertSection(file, section) {
  let text = ''
  if (existsSync(file)) text = readFileSync(file, 'utf8')
  const begin = text.indexOf(MARK_BEGIN)
  const end = text.indexOf(MARK_END)
  if (begin !== -1 && end !== -1 && end > begin) {
    text = text.slice(0, begin) + section + '\n' + text.slice(end + MARK_END.length)
  } else {
    const sticky = text && !text.endsWith('\n\n') ? (text.endsWith('\n') ? '\n' : '\n\n') : ''
    text = text + sticky + section + '\n'
  }
  writeFileSync(file, text)
}

/** Every slug under docs/design/ that has a build-spec or a probe config. */function slugs(project) {
  const base = path.join(project, 'docs', 'design')
  if (!existsSync(base)) return []
  const out = []
  for (const name of readdirSync(base, { withFileTypes: true })) {
    if (!name.isDirectory() || name.name.startsWith('.')) continue
    const dir = path.join(base, name.name)
    if (existsSync(path.join(dir, 'build-spec.json')) || existsSync(path.join(dir, 'design-spec.json')) || existsSync(path.join(dir, 'probe.config.json'))) {
      out.push(name.name)
    }
  }
  return out.sort()
}

export function writeDesignIndex(startDir, { slug, hasBrand, hasProbe } = {}) {
  // The probe may hand us docs/design/<slug>/; walk up to the actual project
  // (the nearest ancestor holding docs/design) before touching anything.
  let project = path.resolve(startDir)
  while (!existsSync(path.join(project, 'docs', 'design')) && project !== path.dirname(project)) project = path.dirname(project)
  if (!existsSync(path.join(project, 'docs', 'design'))) return null
  const slugsFound = slugs(project)
  if (!slugsFound.length && !hasBrand) return null
  const lines = [
    MARK_BEGIN,
    '## Design system context — generated by the design pipeline, edit the sources not this section',
    '',
  ]
  if (hasBrand ?? existsSync(path.join(project, 'docs', 'brand', 'brand.md'))) {
    lines.push(
      '- **Brand record:** [docs/brand/brand.md](./docs/brand/brand.md) — the story; [docs/brand/brand.json](./docs/brand/brand.json) is the machine source of truth. The interview writes both.',
    )
  }
  for (const s of slugsFound) {
    const dir = path.join(project, 'docs', 'design', s)
    const specName = existsSync(path.join(dir, 'build-spec.json')) ? 'build-spec.json' : existsSync(path.join(dir, 'design-spec.json')) ? 'design-spec.json' : null
    const decisionName = existsSync(path.join(dir, '05-decision.md')) ? '05-decision.md' : existsSync(path.join(dir, '05-probe.md')) ? '05-probe.md' : null
    const decision = decisionName ? `[docs/design/${s}/${decisionName}](./docs/design/${s}/${decisionName})` : 'decision pending'
    const spec = specName ? `[${specName}](./docs/design/${s}/${specName}) (machine brief)` : ''
    lines.push(`- **${s}:** ${decision}${spec ? ' · ' + spec : ''} · [02-direction.md](./docs/design/${s}/02-direction.md)`)
  }
  lines.push(
    '',
    'Rules for any agent touching design:',
    '- Read brand.md first; honour banned words, voice rules and forbidden territory.',
    '- The dials in the brand record are targets; the committed direction in the decision doc wins over personal taste.',
    '- These files are generated. To change them, edit the interview answers (`docs/brand/data/`, `docs/design/*/data/`) and re-run the emit.',
    '- For a new page, the entry order is: brand.md → docs/design/<slug>/02-direction.md → 05-decision.md → build-spec.json.',
    MARK_END,
  )
  const section = lines.join('\n') + '\n'

  const written = []
  const agents = path.join(project, 'AGENTS.md')
  mkdirSync(path.join(project, 'docs', 'design'), { recursive: true })
  upsertSection(agents, section)
  written.push(agents)
  const designMd = path.join(project, 'design.md')
  upsertSection(designMd, section)
  written.push(designMd)
  const readme = path.join(project, 'docs', 'design', 'README.md')
  upsertSection(readme, section)
  written.push(readme)
  return written
}
